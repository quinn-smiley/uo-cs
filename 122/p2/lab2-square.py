# Step 1: Define a function that accepts a number
# Step 2: Multiply the number by itself
# Step 3: Return the result
# Step 4: Test with the values 2, 10, and 100

def square(num):
    result = num * num
    return result

print(square(2))
print(square(10))
print(square(100))