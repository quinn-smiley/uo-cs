# 8 — SEARCH FOR SONGS (OPTIONAL)
# Steps:
# 1. Ask the user what field to search by (title or artist).
# 2. Loop through the playlist.
# 3. Compare the user's search term with the dictionary values.
# 4. Display any matching songs.

def search_songs(playlist):
    print("\n--- Search Songs ---")

    if not playlist:
        print("Your playlist is empty.")
        return

    term = input("Enter a word to search for (title or artist): ").lower()

    print("\nResults:")
    found_any = False

    for i, song in enumerate(playlist, start=1):
        title = song["title"].lower()
        artist = song["artist"].lower()

        if term in title or term in artist:
            print(i, song["title"], "-", song["artist"])
            found_any = True

    if not found_any:
        print("No matching songs found.")

