# 6 — REMOVE A SONG
# Steps:
# 1. Display the playlist with song numbers.
# 2. Ask the user which song number to remove.
# 3. Convert the number to a list index.
# 4. Remove the corresponding item from the list.
# 5. Confirm removal.

def delete_song(playlist):
  print("\n--- Remove a Song ---")
  if not playlist:
        print("Your playlist is empty.")
        return

  for i, song in enumerate(playlist, start=1):
        print(i, song["title"], "-", song["artist"])

  choice = input("Enter the number of the song to remove: ")

  index = int(choice) - 1

  removed = playlist.pop(index)

  print("Removed:", removed["title"])


