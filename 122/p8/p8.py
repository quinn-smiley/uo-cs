# 3 — MAIN PROGRAM LOOP
# The program will:
# - Continuously display a menu of options
# - Accept user input
# - Perform actions based on the user's choice
# - Continue until the user chooses to quit

# Possible menu options:
# - Add a song
# - View playlist
# - Remove a song
# - Reorder songs
# - Search for songs
# - Quit

def show_menu():
    print("\n--- Playlist Menu ---")
    print("1. Add a song")
    print("2. View playlist")
    print("3. Remove a song")
    print("4. Reorder songs")
    print("5. Search for songs")
    print("6. Quit")

running = True

while running:
    show_menu()
    choice = input("Enter your choice: ")

    if choice == "1":
        add_song(playlist)

    elif choice == "2":
        view_playlist(playlist)

    elif choice == "3":
        delete_song(playlist)

    elif choice == "4":
        reorder_songs(playlist)

    elif choice == "5":
        search_songs(playlist)

    elif choice == "6":
        print("Goodbye!")
        running = False

    else:
        print("Invalid choice. Please try again.")

