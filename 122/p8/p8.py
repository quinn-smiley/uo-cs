# 7 — REORDER SONGS (OPTIONAL)
# Steps:
# 1. Display the playlist with numbers.
# 2. Ask the user which song to move.
# 3. Ask where it should be moved.
# 4. Remove the song from its current position.
# 5. Insert it into the new position.

def reorder_songs(playlist):
    print("\n--- Reorder Songs ---")

    if not playlist:
        print("Your playlist is empty.")
        return

    for i, song in enumerate(playlist, start=1):
        print(i, song["title"], "-", song["artist"])

    old_pos = int(input("Which song number do you want to move? "))

    new_pos = int(input("Move it to which position? "))

    old_index = old_pos - 1
    new_index = new_pos - 1

    song = playlist.pop(old_index)
    playlist.insert(new_index, song)

    print("Song moved.")


