# 5 — VIEW PLAYLIST
# Steps:
# 1. Check if the playlist is empty.
# 2. If empty, display a message.
# 3. Otherwise, loop through the list and display each song.
# 4. Show song numbers (index + 1) for user reference.

def view_playlist(playlist):
  if playlist:
    count = 0
    for song in playlist:
      count += 1
      print(count, song)
  else:
    print("Playlist does not conatin any songs.")

